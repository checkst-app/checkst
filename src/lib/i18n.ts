const dicts: Record<Lang, Dict> = { de, en };

export type TFunc = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFunc {
  const dict = dicts[lang];
  return (key, vars) => {
    let s: string = dict[key] ?? de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function systemLang(): Lang {
  return navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
}

export const I18nContext = createContext<{ t: TFunc; lang: Lang }>({ t: makeT("de"), lang: "de" });

export function useT() {
  return useContext(I18nContext);
}
